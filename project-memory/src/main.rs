//! project-memory: checks and maintains the project memory under docs/, as
//! the project's docs/MEMORY.md describes. Rust standard library only.
//!
//!   project-memory lint            check notes, links, citations, log names,
//!                                  the index, size budgets and secrets; exit 1
//!                                  on any problem
//!   project-memory index [--check] write docs/INDEX.md from the notes'
//!                                  frontmatter; --check only reports whether it
//!                                  is current
//!   project-memory stale           list what a consolidation pass must look at
//!
//! The project is the nearest directory at or above the current one, up to the
//! git repository root, that has docs/MEMORY.md, or $MEMORY_ROOT when set.
//! Settings come from docs/MEMORY.md's frontmatter.

mod date;
mod frontmatter;
mod scan;

use std::cell::RefCell;
use std::collections::{BTreeMap, HashMap};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::exit;

use frontmatter::Fields;

/// (type, folder, title) in index order.
const TYPES: [(&str, &str, &str); 5] = [
    ("convention", "conventions", "Conventions"),
    ("architecture", "architecture", "Architecture"),
    ("decision", "decisions", "Decisions"),
    ("playbook", "playbooks", "Playbooks"),
    ("gotcha", "gotchas", "Gotchas"),
];
const STATUSES: [&str; 4] = ["proposed", "active", "superseded", "expired"];
const REQUIRED: [&str; 5] = ["id", "type", "status", "summary", "created"];
const DATE_FIELDS: [&str; 3] = ["created", "verified_at", "valid_until"];
const LIST_FIELDS: [&str; 4] = ["aliases", "citations", "sources", "links"];
const GENERATED: &str =
    "<!-- Generated by project-memory index from the notes' frontmatter. Do not edit; run project-memory index. -->";
/// The part of the marker that every version has written, so an index from
/// an older version (the Ruby bin/memory) is still known as generated.
const GENERATED_ANY: &str = "index from the notes' frontmatter. Do not edit; run ";
const USAGE: &str = "usage: project-memory lint | index [--check] | stale";

fn folder_of(kind: &str) -> Option<&'static str> {
    TYPES.iter().find(|t| t.0 == kind).map(|t| t.1)
}

fn is_type_folder(folder: &str) -> bool {
    TYPES.iter().any(|t| t.1 == folder)
}

struct Settings {
    root_context_max_lines: usize,
    index_max_lines: usize,
    expire_after_days: i64,
}

struct Note {
    path: PathBuf,
    /// Path relative to docs/, with forward slashes.
    rel: String,
    /// The first folder under docs/: a type folder, inbox or archive.
    area: String,
    /// The type folder: the area, or the folder under archive/.
    folder: String,
    fields: Option<Fields>,
    errors: Vec<String>,
    body: String,
}

impl Note {
    fn field(&self, key: &str) -> Option<&str> {
        self.fields.as_ref().and_then(|f| f.text(key))
    }

    fn curated_active(&self) -> bool {
        self.area != "inbox" && self.area != "archive" && self.field("status") == Some("active")
    }
}

struct Lesson {
    id: String,
    title: String,
    counts: Option<(u64, u64)>,
    line: usize,
}

struct Memory {
    root: PathBuf,
    docs: PathBuf,
    settings: Settings,
    notes: Vec<Note>,
    lessons: Vec<Lesson>,
    lesson_problems: Vec<String>,
    /// Line counts of cited files, so each is read once.
    line_counts: RefCell<HashMap<PathBuf, usize>>,
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let args: Vec<&str> = args.iter().map(String::as_str).collect();
    let command = match args.as_slice() {
        ["lint"] => "lint",
        ["index"] => "index",
        ["index", "--check"] => "check",
        ["stale"] => "stale",
        ["-h"] | ["--help"] | ["help"] => {
            println!("{}", USAGE);
            return;
        }
        _ => {
            eprintln!("{}", USAGE);
            exit(2);
        }
    };
    let root = find_root().unwrap_or_else(|| {
        eprintln!(
            "project-memory: no docs/MEMORY.md here or above (up to the git root); set up project memory with the project-memory skill"
        );
        exit(1);
    });
    let memory = Memory::load(root);
    match command {
        "lint" => memory.lint(),
        "index" => memory.write_index(),
        "check" => memory.check_index(),
        _ => memory.stale(),
    }
}

fn find_root() -> Option<PathBuf> {
    if let Some(root) = std::env::var_os("MEMORY_ROOT") {
        let root = PathBuf::from(root);
        return root.join("docs/MEMORY.md").is_file().then_some(root);
    }
    let cwd = std::env::current_dir().ok()?;
    for dir in cwd.ancestors() {
        if dir.join("docs/MEMORY.md").is_file() {
            return Some(dir.to_path_buf());
        }
        if dir.join(".git").exists() {
            break;
        }
    }
    None
}

fn read(path: &Path) -> String {
    fs::read(path).map(|bytes| String::from_utf8_lossy(&bytes).into_owned()).unwrap_or_default()
}

fn line_count(text: &str) -> usize {
    text.matches('\n').count() + usize::from(!text.is_empty() && !text.ends_with('\n'))
}

/// Every file under `dir`, sorted. Symlinked folders are not followed.
fn files_under(dir: &Path, dotfiles: bool) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(current) = stack.pop() {
        let Ok(entries) = fs::read_dir(&current) else { continue };
        for entry in entries.flatten() {
            let path = entry.path();
            if !dotfiles && entry.file_name().to_string_lossy().starts_with('.') {
                continue;
            }
            match entry.file_type() {
                Ok(t) if t.is_dir() => stack.push(path),
                _ if path.is_file() => out.push(path),
                _ => {}
            }
        }
    }
    out.sort();
    out
}

fn relative(path: &Path, base: &Path) -> String {
    path.strip_prefix(base).unwrap_or(path).to_string_lossy().replace('\\', "/")
}

impl Memory {
    fn load(root: PathBuf) -> Memory {
        let docs = root.join("docs");
        let protocol = frontmatter::parse(&read(&docs.join("MEMORY.md")));
        let number = |key: &str, default: i64| {
            protocol
                .fields
                .as_ref()
                .and_then(|f| f.text(key))
                .filter(|v| v.bytes().all(|c| c.is_ascii_digit()))
                .and_then(|v| v.parse::<i64>().ok())
                .unwrap_or(default)
        };
        let settings = Settings {
            root_context_max_lines: number("root_context_max_lines", 150) as usize,
            index_max_lines: number("index_max_lines", 200) as usize,
            expire_after_days: number("expire_after_days", 90),
        };
        let mut paths: Vec<PathBuf> = TYPES
            .iter()
            .map(|t| t.1)
            .chain(["inbox", "archive"])
            .flat_map(|folder| files_under(&docs.join(folder), false))
            .filter(|p| p.extension().is_some_and(|e| e == "md"))
            .filter(|p| p.file_name().is_some_and(|n| n != "INDEX.md"))
            .filter(|p| relative(p, &docs) != "archive/lessons.md")
            .collect();
        paths.sort();
        let notes = paths
            .into_iter()
            .map(|path| {
                let rel = relative(&path, &docs);
                let parts: Vec<&str> = rel.split('/').collect();
                let area = parts[0].to_string();
                let folder = if area == "archive" && parts.len() > 2 { parts[1].to_string() } else { area.clone() };
                let parsed = frontmatter::parse(&read(&path));
                Note { path, rel, area, folder, fields: parsed.fields, errors: parsed.errors, body: parsed.body }
            })
            .collect();
        let (lessons, lesson_problems) = parse_lessons(&read(&docs.join("lessons.md")));
        Memory { root, docs, settings, notes, lessons, lesson_problems, line_counts: RefCell::default() }
    }

    fn rel(&self, path: &Path) -> String {
        relative(path, &self.root)
    }

    // -- lint ----------------------------------------------------------------

    fn note_problems(&self, note: &Note, ids: &BTreeMap<String, Vec<&Note>>) -> Vec<String> {
        let Some(fields) = &note.fields else { return note.errors.clone() };
        let mut problems = note.errors.clone();
        for key in REQUIRED {
            if fields.text(key).is_none() {
                problems.push(format!("missing {}", key));
            }
        }
        for key in LIST_FIELDS {
            if fields.text(key).is_some() {
                problems.push(format!("{} must be a list: [a, b]", key));
            }
        }
        for key in DATE_FIELDS {
            if fields.has(key) && fields.text(key).and_then(date::parse).is_none() {
                let shown = fields.text(key).map(str::to_string).unwrap_or_else(|| fields.list(key).join(", "));
                problems.push(format!("{} is not a date (YYYY-MM-DD): {}", key, shown));
            }
        }
        let kind = fields.text("type");
        let status = fields.text("status");
        if let Some(kind) = kind.filter(|k| folder_of(k).is_none()) {
            let names: Vec<&str> = TYPES.iter().map(|t| t.0).collect();
            problems.push(format!("unknown type {}: use one of {}", kind, names.join(", ")));
        }
        if let Some(status) = status.filter(|s| !STATUSES.contains(s)) {
            problems.push(format!("unknown status {}: use one of {}", status, STATUSES.join(", ")));
        }
        if status == Some("active") && fields.text("verified_at").is_none() {
            problems.push("active notes need verified_at".to_string());
        }
        if status == Some("superseded") && fields.text("superseded_by").is_none() {
            problems.push("superseded notes need superseded_by".to_string());
        }
        if let Some(by) = fields.text("superseded_by").filter(|by| !ids.contains_key(*by)) {
            problems.push(format!("superseded_by {} is not the id of any note", by));
        }
        let shown = status.unwrap_or("");
        match note.area.as_str() {
            "inbox" => {
                if status.is_some() && status != Some("proposed") {
                    problems.push(format!("only proposals belong in inbox/ (status is {})", shown));
                }
            }
            "archive" => {
                if matches!(status, Some("active") | Some("proposed")) {
                    problems.push(format!("only superseded or expired notes belong in archive/ (status is {})", shown));
                }
            }
            _ => {
                if status == Some("proposed") {
                    problems.push("status: proposed belongs in inbox/".to_string());
                }
                if matches!(status, Some("superseded") | Some("expired")) {
                    problems.push(format!("{} notes belong in archive/", shown));
                }
            }
        }
        if let Some(folder) = kind.and_then(folder_of) {
            if note.area != "inbox" && is_type_folder(&note.folder) && folder != note.folder {
                problems.push(format!("type {} belongs in {}/", kind.unwrap_or(""), folder));
            }
        }
        if note.area != "archive" {
            for citation in fields.list("citations") {
                problems.extend(self.citation_problems(&citation));
            }
            for link in fields.list("links") {
                let target = link.split('#').next().unwrap_or("");
                if !self.docs.join(target).exists() {
                    problems.push(format!("link {} does not exist", link));
                }
            }
            problems.extend(link_problems(&note.path, &note.body));
        }
        problems
    }

    fn citation_problems(&self, citation: &str) -> Vec<String> {
        let (file, lines) = split_citation(citation);
        let path = self.root.join(file);
        if !path.is_file() {
            return vec![format!("citation {}: {} does not exist", citation, file)];
        }
        let Some((first, last)) = lines else { return Vec::new() };
        let count = *self.line_counts.borrow_mut().entry(path.clone()).or_insert_with(|| line_count(&read(&path)));
        if last > count || first < 1 {
            return vec![format!("citation {}: {} has only {} lines", citation, file, count)];
        }
        Vec::new()
    }

    fn log_problems(&self) -> Vec<String> {
        let mut problems = Vec::new();
        for file in files_under(&self.docs.join("log"), true) {
            let name = relative(&file, &self.docs);
            match parse_log_name(&name) {
                None => problems.push(format!("{}: log entries are named log/YYYY/MM/DD/EPOCH-slug.md", self.rel(&file))),
                Some((day, epoch)) => {
                    let actual = date::utc_path(epoch);
                    if actual != day {
                        problems.push(format!("{}: epoch {} is {} in UTC, not {}", self.rel(&file), epoch, actual, day));
                    }
                }
            }
        }
        problems
    }

    fn secret_problems(&self) -> Vec<String> {
        let mut problems = Vec::new();
        for file in files_under(&self.docs, true) {
            let bytes = fs::read(&file).unwrap_or_default();
            for (index, line) in bytes.split(|&c| c == b'\n').enumerate() {
                for name in scan::secrets(line) {
                    problems.push(format!("{}:{}: looks like {}; remove it and rotate it", self.rel(&file), index + 1, name));
                }
            }
        }
        problems
    }

    fn size_problems(&self) -> Vec<String> {
        let mut problems = Vec::new();
        if let Some(root) = ["CLAUDE.md", "AGENTS.md"].iter().map(|n| self.root.join(n)).find(|p| p.is_file()) {
            let lines = line_count(&read(&root));
            let max = self.settings.root_context_max_lines;
            if lines > max {
                problems.push(format!(
                    "{}: {} lines, over root_context_max_lines ({}); move detail into docs/ notes",
                    self.rel(&root),
                    lines,
                    max
                ));
            }
        }
        let index = self.docs.join("INDEX.md");
        if index.is_file() {
            let lines = line_count(&read(&index));
            let max = self.settings.index_max_lines;
            if lines > max {
                problems.push(format!("docs/INDEX.md: {} lines, over index_max_lines ({})", lines, max));
            }
        }
        problems
    }

    fn lint(&self) {
        let mut problems = Vec::new();
        if self.docs.join("history").is_dir() {
            problems.push("docs/history/ is a legacy log: migrate it with the project-memory skill".to_string());
        }
        if self.docs.join("HISTORY.md").is_file() {
            problems.push("docs/HISTORY.md is a legacy log: migrate it with the project-memory skill".to_string());
        }
        let mut ids: BTreeMap<String, Vec<&Note>> = BTreeMap::new();
        let mut order: Vec<String> = Vec::new();
        for note in &self.notes {
            if let Some(id) = note.field("id") {
                if !ids.contains_key(id) {
                    order.push(id.to_string());
                }
                ids.entry(id.to_string()).or_default().push(note);
            }
        }
        for id in &order {
            let group = &ids[id];
            if group.len() > 1 {
                let paths: Vec<String> = group.iter().map(|n| self.rel(&n.path)).collect();
                problems.push(format!("id {} is used by {}", id, paths.join(" and ")));
            }
        }
        for note in &self.notes {
            for problem in self.note_problems(note, &ids) {
                problems.push(format!("{}: {}", self.rel(&note.path), problem));
            }
        }
        problems.extend(self.lesson_problems.iter().map(|p| format!("docs/{}", p)));
        let lessons = self.docs.join("lessons.md");
        if lessons.is_file() {
            problems.extend(link_problems(&lessons, &read(&lessons)).into_iter().map(|p| format!("docs/lessons.md: {}", p)));
        }
        problems.extend(self.log_problems());
        for file in self.index_differences() {
            problems.push(format!("{} is out of date: run project-memory index", self.rel(&file)));
        }
        problems.extend(self.size_problems());
        problems.extend(self.secret_problems());
        if problems.is_empty() {
            println!("Memory docs are clean: {} note(s), {} lesson(s).", self.notes.len(), self.lessons.len());
            return;
        }
        for problem in &problems {
            println!("{}", problem);
        }
        println!("{} problem(s).", problems.len());
        exit(1);
    }

    // -- index ---------------------------------------------------------------

    /// Every generated file as (path, content): one INDEX.md per folder when a
    /// single docs/INDEX.md would pass index_max_lines, then docs/INDEX.md.
    fn index_files(&self) -> Vec<(PathBuf, String)> {
        let line = |note: &Note| {
            let verified = note.field("verified_at").map(|v| format!(" (verified {})", v)).unwrap_or_default();
            format!("- {} - {}{}", note.rel, note.field("summary").unwrap_or(""), verified)
        };
        let groups: Vec<(&str, &str, Vec<&Note>)> = TYPES
            .iter()
            .map(|t| (t.1, t.2, self.notes.iter().filter(|n| n.curated_active() && n.folder == t.1).collect::<Vec<_>>()))
            .filter(|g| !g.2.is_empty())
            .collect();
        let proposals = self.notes.iter().filter(|n| n.area == "inbox").count();
        let head = vec![
            "# Index".to_string(),
            String::new(),
            GENERATED.to_string(),
            String::new(),
            "Read this at the start of a task and open only the notes that matter to it. Protocol: MEMORY.md.".to_string(),
        ];
        let mut tail = Vec::new();
        if !self.lessons.is_empty() {
            tail.extend([String::new(), "## Lessons".to_string()]);
            tail.push(format!("- lessons.md - {} lesson(s); skim the titles.", self.lessons.len()));
        }
        if proposals > 0 {
            tail.extend([String::new(), "## Inbox".to_string()]);
            tail.push(format!("- inbox/ - {} proposal(s) awaiting verification; never guidance.", proposals));
        }
        let mut body: Vec<String> = Vec::new();
        for (_, title, notes) in &groups {
            body.extend([String::new(), format!("## {}", title)]);
            body.extend(notes.iter().map(|n| line(n)));
        }
        if groups.is_empty() {
            body = vec![String::new(), "No curated notes yet.".to_string()];
        }
        let mut files = Vec::new();
        if head.len() + body.len() + tail.len() > self.settings.index_max_lines {
            body = vec![String::new(), "## Folders".to_string()];
            for (folder, title, notes) in &groups {
                body.push(format!("- {}/INDEX.md - {} {} note(s)", folder, notes.len(), title.to_lowercase()));
                let mut lines = vec![
                    format!("# {} index", title),
                    String::new(),
                    GENERATED.to_string(),
                    String::new(),
                    "Paths are relative to docs/.".to_string(),
                    String::new(),
                ];
                lines.extend(notes.iter().map(|n| line(n)));
                files.push((self.docs.join(folder).join("INDEX.md"), lines.join("\n") + "\n"));
            }
        }
        let all: Vec<String> = head.into_iter().chain(body).chain(tail).collect();
        files.push((self.docs.join("INDEX.md"), all.join("\n") + "\n"));
        files
    }

    /// Generated folder indexes that the current notes no longer need.
    fn stale_folder_indexes(&self, wanted: &[(PathBuf, String)]) -> Vec<PathBuf> {
        let Ok(entries) = fs::read_dir(&self.docs) else { return Vec::new() };
        let mut found: Vec<PathBuf> = entries
            .flatten()
            .map(|e| e.path().join("INDEX.md"))
            .filter(|p| p.is_file() && !wanted.iter().any(|w| &w.0 == p) && read(p).contains(GENERATED_ANY))
            .collect();
        found.sort();
        found
    }

    fn index_differences(&self) -> Vec<PathBuf> {
        let wanted = self.index_files();
        let mut changed: Vec<PathBuf> =
            wanted.iter().filter(|(path, content)| !path.is_file() || &read(path) != content).map(|(p, _)| p.clone()).collect();
        changed.extend(self.stale_folder_indexes(&wanted));
        changed
    }

    fn write_index(&self) {
        let wanted = self.index_files();
        let main_index = self.docs.join("INDEX.md");
        for (path, _) in &wanted {
            if path != &main_index && path.is_file() && !read(path).contains(GENERATED_ANY) {
                eprintln!(
                    "project-memory: {} exists and was not written by project-memory index; rename it, then run this again",
                    self.rel(path)
                );
                exit(1);
            }
        }
        for (path, content) in &wanted {
            if !path.is_file() || &read(path) != content {
                if let Err(e) = fs::write(path, content) {
                    eprintln!("project-memory: cannot write {}: {}", self.rel(path), e);
                    exit(1);
                }
            }
        }
        for path in self.stale_folder_indexes(&wanted) {
            let _ = fs::remove_file(path);
        }
        let names: Vec<String> = wanted.iter().map(|(p, _)| self.rel(p)).collect();
        println!("Wrote {}.", names.join(", "));
    }

    fn check_index(&self) {
        let stale = self.index_differences();
        if stale.is_empty() {
            println!("docs/INDEX.md is current.");
            return;
        }
        for path in stale {
            println!("{} is out of date: run project-memory index", self.rel(&path));
        }
        exit(1);
    }

    // -- stale ---------------------------------------------------------------

    fn stale(&self) {
        let today = date::today();
        let window = self.settings.expire_after_days;
        let mut sections: Vec<(String, Vec<String>)> = Vec::new();
        let proposals = self
            .notes
            .iter()
            .filter(|n| n.area == "inbox")
            .map(|n| {
                let age = match n.field("created").and_then(date::parse) {
                    Some(created) => format!("{} day(s) old", today - created),
                    None => "no created date".to_string(),
                };
                format!("- {} ({}): {}", self.rel(&n.path), age, n.field("summary").unwrap_or(""))
            })
            .collect();
        sections.push(("Inbox proposals to promote or reject".to_string(), proposals));
        let expiring = self
            .notes
            .iter()
            .filter(|n| n.curated_active())
            .filter_map(|n| match n.field("verified_at").and_then(date::parse) {
                None => Some(format!("- {}: no valid verified_at", self.rel(&n.path))),
                Some(verified) if today - verified > window => Some(format!(
                    "- {}: verified {}, {} day(s) ago",
                    self.rel(&n.path),
                    n.field("verified_at").unwrap_or(""),
                    today - verified
                )),
                _ => None,
            })
            .collect();
        sections.push((format!("Notes not verified in {} days: re-verify or expire", window), expiring));
        let harmful = self
            .lessons
            .iter()
            .filter_map(|l| match l.counts {
                Some((helpful, harmful)) if harmful > 0 && harmful >= helpful => {
                    Some(format!("- {} {} (helpful {}, harmful {})", l.id, l.title, helpful, harmful))
                }
                _ => None,
            })
            .collect();
        sections.push(("Lessons to retire (harmful >= helpful)".to_string(), harmful));
        sections.retain(|(_, lines)| !lines.is_empty());
        if sections.is_empty() {
            println!("Nothing to consolidate.");
            return;
        }
        let text: Vec<String> = sections.iter().map(|(title, lines)| format!("{}:\n{}", title, lines.join("\n"))).collect();
        println!("{}", text.join("\n\n"));
    }
}

/// A citation's file and, when given, its first and last line.
fn split_citation(citation: &str) -> (&str, Option<(usize, usize)>) {
    if let Some((file, lines)) = citation.rsplit_once(':') {
        let numbers: Vec<&str> = lines.splitn(2, '-').collect();
        let parsed: Option<Vec<usize>> = numbers
            .iter()
            .map(|n| (!n.is_empty() && n.bytes().all(|c| c.is_ascii_digit())).then(|| n.parse().ok()).flatten())
            .collect();
        if let (false, Some(parsed)) = (file.is_empty(), parsed) {
            return (file, Some((parsed[0], *parsed.last().unwrap_or(&parsed[0]))));
        }
    }
    (citation, None)
}

/// The YYYY/MM/DD folder and epoch of a log/YYYY/MM/DD/EPOCH-slug.md path.
fn parse_log_name(name: &str) -> Option<(String, i64)> {
    let parts: Vec<&str> = name.split('/').collect();
    let digits = |s: &str, n: usize| s.len() == n && s.bytes().all(|c| c.is_ascii_digit());
    if parts.len() != 5 || parts[0] != "log" || !digits(parts[1], 4) || !digits(parts[2], 2) || !digits(parts[3], 2) {
        return None;
    }
    let stem = parts[4].strip_suffix(".md")?;
    let (epoch, slug) = stem.split_once('-')?;
    if epoch.is_empty() || slug.is_empty() || !epoch.bytes().all(|c| c.is_ascii_digit()) {
        return None;
    }
    Some((format!("{}/{}/{}", parts[1], parts[2], parts[3]), epoch.parse().ok()?))
}

fn link_problems(file: &Path, text: &str) -> Vec<String> {
    let dir = file.parent().unwrap_or(Path::new("."));
    scan::relative_links(text)
        .into_iter()
        .filter(|target| !dir.join(target.split('#').next().unwrap_or("")).exists())
        .map(|target| format!("link {} does not exist", target))
        .collect()
}

/// Lessons from lessons.md, with problems in its format.
fn parse_lessons(text: &str) -> (Vec<Lesson>, Vec<String>) {
    let mut lessons: Vec<Lesson> = Vec::new();
    let mut problems = Vec::new();
    let missing = |l: &Lesson| format!("lessons.md:{}: {} has no `helpful: N | harmful: N | last_used: ...` line", l.line, l.id);
    for (index, line) in text.lines().enumerate() {
        if let Some((id, title)) = lesson_head(line) {
            if let Some(last) = lessons.last().filter(|l| l.counts.is_none()) {
                problems.push(missing(last));
            }
            lessons.push(Lesson { id, title, counts: None, line: index + 1 });
        } else if let (Some(last), Some(counts)) = (lessons.last_mut(), lesson_counts(line)) {
            last.counts = Some(counts);
        } else if line.starts_with("- [") {
            problems.push(format!("lessons.md:{}: a lesson starts with `- [L-NNN] Title`", index + 1));
        }
    }
    if let Some(last) = lessons.last().filter(|l| l.counts.is_none()) {
        problems.push(missing(last));
    }
    let mut seen: Vec<(&str, usize)> = Vec::new();
    for lesson in &lessons {
        match seen.iter_mut().find(|(id, _)| *id == lesson.id) {
            Some(entry) => entry.1 += 1,
            None => seen.push((&lesson.id, 1)),
        }
    }
    for (id, count) in seen.into_iter().filter(|(_, count)| *count > 1) {
        problems.push(format!("lessons.md: {} is used {} times", id, count));
    }
    (lessons, problems)
}

/// `- [L-042] Title` as ("L-042", "Title").
fn lesson_head(line: &str) -> Option<(String, String)> {
    let rest = line.strip_prefix("- [L-")?;
    let close = rest.find(']')?;
    let number = &rest[..close];
    let title = &rest[close + 1..];
    if number.is_empty() || !number.bytes().all(|c| c.is_ascii_digit()) || !title.starts_with(char::is_whitespace) || title.trim().is_empty() {
        return None;
    }
    Some((format!("L-{}", number), title.trim().to_string()))
}

/// An indented `helpful: N | harmful: N ...` line as (helpful, harmful).
fn lesson_counts(line: &str) -> Option<(u64, u64)> {
    if !line.starts_with(char::is_whitespace) {
        return None;
    }
    let mut parts = line.trim().split('|').map(str::trim);
    let number = |part: Option<&str>, key: &str| part?.strip_prefix(key)?.trim().parse::<u64>().ok();
    Some((number(parts.next(), "helpful:")?, number(parts.next(), "harmful:")?))
}

